"""Export the derived per-layer constants the KSP plugin and shader need.

Writes GameData/RealAirglow/Config/Earth.cfg (ModuleManager-patchable AIRGLOW node). Raw
third-party tables stay in the reference cache; only derived numbers are written, with
attribution comments (docs/PHYSICS.md §14).

Per layer:
* profile (asymmetric Gaussian: peak, HWHM below/above) and zenith intensity at 100 sfu;
* solarCoefficient: relative change per 100 sfu, camera-luminance-weighted over the lines;
* cameraRGB / cieRGB: linear sRGB per rayleigh of apparent column (luminance units cd m^-2),
  for the Nikon D3 camera response and the CIE 1931 observer;
* scotopicY: scotopic luminance (cd m^-2) per rayleigh, for the eye mode;
* sigmaRayleigh / sigmaOzone (m^2) and aerosolFactor per camera channel: response-weighted
  means for the extinction terms (first order in optical depth; docs/PHYSICS.md §11).
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from airglow_ref import atmosphere, colour, data, layers
from airglow_ref.colour import GRID_NM, component_spectrum

OUT = Path(__file__).resolve().parent.parent / "GameData" / "RealAirglow" / "Config" / "Earth.cfg"


def channel_means(comp, resp, quantity_nm):
    """Response-weighted mean of a spectral quantity per output channel (camera RGB space
    before the colour matrix, so weights are positive)."""
    line_nm, line_W, cont_W = component_spectrum(comp)
    wl, wc = resp.weights(line_nm), resp.weights(GRID_NM)
    ql, qc = quantity_nm(line_nm), quantity_nm(GRID_NM)
    num = (line_W * ql) @ wl + (cont_W * qc) @ wc
    den = line_W @ wl + cont_W @ wc
    return np.where(den > 0, num / np.where(den > 0, den, 1), 0.0)


def air_density_fit(top_km=60.0, degree=5):
    """Polynomial fit ln n(z) = sum_k c_k (z/top)^k to MSIS total density, 0-top km
    (equinox midnight, 40 N). Returns (coefficients, max local error, column error)."""
    z = np.linspace(0, top_km, 601)
    n = atmosphere.msis_profile(z)["total"]
    c = np.polynomial.polynomial.polyfit(z / top_km, np.log(n), degree)
    fit = np.exp(np.polynomial.polynomial.polyval(z / top_km, c))
    return c, np.max(np.abs(fit / n - 1)), np.trapezoid(fit, z) / np.trapezoid(n, z) - 1


def fmt(v):
    return ", ".join(f"{x:.6g}" for x in np.atleast_1d(v))


def main():
    comps = layers.default_components()
    cam, cie = colour.camera_response(), colour.cie_response()
    lower = atmosphere.LowerAtmosphere()
    lam_o3, sig_o3 = data.ozone_cross_section(lower.ozone_temperature_K)
    coef, err, col_err = air_density_fit(lower.top_km)

    lines = [
        "// RealAirglow layer definitions for Earth. GENERATED by reference/export_ksp_config.py;",
        "// do not edit by hand, edit docs/PHYSICS.md and the reference model, then re-export.",
        "// Derived from: PALACE v1.0 data (Noll et al. 2025, CC BY 4.0); CIE 1931 CMFs and",
        "// V'(lambda) (CIE, CC BY-SA 4.0); Nikon D3 sensitivities (Jiang et al. 2013, CC BY-NC-SA",
        "// 4.0); Bodhaine et al. 1999; Serdyuchenko et al. 2014; NRLMSIS 2.1.",
        "AIRGLOW",
        "{",
        "\tbody = Earth",
        "\tf107Reference = 100   // sfu, PALACE reference",
        "\tLOWER_ATMOSPHERE",
        "\t{",
        f"\t\t// Air number density: ln(n / m^-3) = sum_k c_k (z / top_km)^k, fit to NRLMSIS 2.1",
        f"\t\t// 0-{lower.top_km:g} km (max local error {err:.1%}, vertical column error {col_err:.2%})",
        f"\t\tairLogDensityPoly = {fmt(coef)}",
        f"\t\tozoneColumn_DU = {lower.ozone_column_DU:g}   // tuning",
        f"\t\tozonePeak_km = {lower.ozone_peak_km:g}   // tuning",
        f"\t\tozoneFwhm_km = {lower.ozone_fwhm_km:g}   // tuning",
        f"\t\taerosolTau550 = {lower.aerosol_tau_550:g}   // tuning",
        f"\t\taerosolScaleHeight_km = {lower.aerosol_scale_height_km:g}   // tuning",
        f"\t\ttop_km = {lower.top_km:g}",
        "\t}",
    ]
    for c in comps:
        rgb_cam = cam.component_rgb(c)
        rgb_cie = cie.component_rgb(c)
        _, Ls = colour.luminances(c)
        lum = cam.component_rgb(c) @ colour.LUMA
        # Camera-luminance-weighted solar coefficient over the component's visible lines.
        line_nm, line_W, cont_W = component_spectrum(c)
        Yl = line_W * (cam.weights(line_nm) @ cam.to_rgb.T @ colour.LUMA) if line_nm.size else np.zeros(0)
        Yc = cont_W @ (cam.weights(GRID_NM) @ cam.to_rgb.T @ colour.LUMA)
        msce_lines = c.line_msce[(c.line_nm >= GRID_NM[0]) & (c.line_nm <= GRID_NM[-1])]
        num = (Yl * msce_lines).sum() + Yc * c.cont_msce
        den = Yl.sum() + Yc
        msce = num / den if den > 0 else 0.0
        sR = channel_means(c, cam, atmosphere.rayleigh_cross_section)
        sO = channel_means(c, cam, lambda l: np.interp(l, lam_o3, sig_o3))
        aF = channel_means(c, cam, lower.aerosol_spectral_factor)
        p = c.profile
        lines += [
            "\tLAYER",
            "\t{",
            f"\t\tname = {c.name}",
            f"\t\tgroup = {c.group}",
            f"\t\tenabled = {str(c.enabled)}",
            f"\t\tpeak_km = {p.peak_km:g}",
            f"\t\thwhmLow_km = {p.hwhm_lo_km:g}",
            f"\t\thwhmHigh_km = {p.hwhm_hi_km:g}",
            f"\t\tintensity_R = {c.intensity_R:.6g}   // zenith, 100 sfu, no extinction",
            f"\t\tsolarCoefficient = {msce:.4g}   // per 100 sfu, camera-luminance weighted",
            f"\t\tcameraRGB = {fmt(rgb_cam)}   // linear sRGB, cd m^-2 per R",
            f"\t\tcieRGB = {fmt(rgb_cie)}",
            f"\t\tscotopicY = {Ls:.6g}",
            f"\t\tsigmaRayleigh = {fmt(sR)}   // m^2, per camera channel",
            f"\t\tsigmaOzone = {fmt(sO)}",
            f"\t\taerosolFactor = {fmt(aF)}",
            "\t}",
        ]
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}  (air fit max error {err:.2%})")


if __name__ == "__main__":
    main()
